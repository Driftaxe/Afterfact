import type { Report, ClaimResultItem } from '@/lib/contracts/report';

/**
 * Scrubs private tokens, internal database IDs, and sensitive worker leases from a report snapshot
 * to create a sanitized public export payload.
 */
export function sanitizeReportForExport(report: Report): Record<string, unknown> {
  return {
    id: report.id,
    mode: report.mode,
    asOfDate: report.asOfDate ?? null,
    createdAt: report.createdAt ?? null,
    answerText: report.answerText,
    summary: report.summary,
    claims: report.claims.map((claim: ClaimResultItem) => ({
      id: claim.id,
      ordinal: claim.ordinal,
      rawText: claim.rawText,
      state: claim.state,
      verdict: 'verdict' in claim ? claim.verdict : null,
      score: 'score' in claim ? claim.score : null,
      reasonCode: 'reasonCode' in claim ? claim.reasonCode : null,
      scoreReason: 'scoreReason' in claim ? claim.scoreReason : null,
      timeline: 'timeline' in claim ? claim.timeline : undefined,
      correction: 'correction' in claim ? claim.correction : undefined,
      evidenceIds: claim.evidenceIds ?? [],
    })),
    evidence: report.evidence.map((evi) => ({
      id: evi.id,
      url: evi.url,
      title: evi.title,
      publisher: evi.publisher,
      publicationDate: evi.publicationDate,
      effectiveDate: evi.effectiveDate,
      retrievedAt: evi.retrievedAt,
      passage: evi.passage,
    })),
  };
}

/**
 * Formats a verification report as a structured, pretty-printed JSON string.
 */
export function formatReportAsJson(report: Report): string {
  const sanitized = sanitizeReportForExport(report);
  return JSON.stringify(sanitized, null, 2);
}

/**
 * Formats a verification report as a clean, publication-ready Markdown bundle.
 */
export function formatReportAsMarkdown(report: Report): string {
  const dateStr = report.asOfDate || new Date().toISOString().split('T')[0];
  const lines: string[] = [];

  // Header & Metadata
  lines.push(`# Verification Report — ${report.id}`);
  lines.push('');
  lines.push(`> Generated by **Afterfact** temporal verification & drift detection engine.`);
  lines.push('');
  lines.push('| Attribute | Value |');
  lines.push('| :--- | :--- |');
  lines.push(`| **Run ID** | \`${report.id}\` |`);
  lines.push(`| **Mode** | ${report.mode.toUpperCase()} |`);
  lines.push(`| **Target As-Of Date** | ${dateStr} |`);
  lines.push(`| **Status** | ${report.state.toUpperCase()} |`);
  lines.push(`| **Total Claims** | ${report.summary.totalClaims} |`);
  lines.push(`| **Supported** | ${report.summary.supported} |`);
  lines.push(`| **Outdated** | ${report.summary.outdated} |`);
  lines.push(`| **Contradicted** | ${report.summary.contradicted} |`);
  lines.push(`| **Unresolved** | ${report.summary.unresolved} |`);
  lines.push('');

  // Original Text
  lines.push('## Evaluated Text');
  lines.push('');
  lines.push('```text');
  lines.push((report.answerText ?? '').trim());
  lines.push('```');
  lines.push('');

  // Detailed Claim Findings
  lines.push('## Claim Assessments');
  lines.push('');

  report.claims.forEach((claim, idx) => {
    lines.push(`### Claim ${idx + 1}: “${claim.rawText}”`);
    lines.push('');

    if (claim.state === 'assessed') {
      const verdictUpper = claim.verdict.toUpperCase().replace(/_/g, ' ');
      const scoreStr = claim.score !== null ? `${claim.score}/100` : 'N/A';
      lines.push(`- **Verdict:** \`${verdictUpper}\` (Freshness Score: **${scoreStr}**)`);
      lines.push(`- **Reason Code:** \`${claim.reasonCode}\``);
      lines.push(`- **Decision Reason:** ${claim.scoreReason}`);

      // Surgical Correction Diff
      if (claim.correction) {
        lines.push('');
        lines.push('#### Surgical Correction Diff:');
        lines.push('```diff');
        lines.push(claim.correction.diff);
        lines.push('```');
      }

      // Then vs. Now Chronology
      if (claim.timeline && claim.timeline.length > 0) {
        lines.push('');
        lines.push('#### Then vs. Now Progression:');
        claim.timeline.forEach((t) => {
          const effective = t.effectiveDate ? ` (Effective: ${t.effectiveDate})` : '';
          const announced = t.announcementDate ? ` [Announced: ${t.announcementDate}]` : '';
          lines.push(`- **[${t.state.toUpperCase()}]** ${t.summary}${effective}${announced}`);
        });
      }
    } else if (claim.state === 'failed') {
      lines.push(`- **State:** FAILED`);
      lines.push(`- **Error:** ${claim.error}`);
    } else {
      lines.push(`- **State:** In Progress (${claim.state})`);
    }

    lines.push('');
  });

  // Cited Evidence Units
  lines.push('## Cited Authoritative Evidence');
  lines.push('');

  if (report.evidence.length === 0) {
    lines.push('_No external web evidence passages recorded for this report._');
  } else {
    report.evidence.forEach((evi, idx) => {
      lines.push(`### [E${idx + 1}] ${evi.title || evi.publisher || 'Web Evidence'}`);
      lines.push(`- **URL:** [${evi.url}](${evi.url})`);
      if (evi.publisher) lines.push(`- **Publisher:** ${evi.publisher}`);
      if (evi.publicationDate) lines.push(`- **Publication Date:** ${evi.publicationDate}`);
      if (evi.effectiveDate) lines.push(`- **Effective Date:** ${evi.effectiveDate}`);
      lines.push('');
      lines.push('> ' + evi.passage.replace(/\n/g, '\n> '));
      lines.push('');
    });
  }

  return lines.join('\n');
}

/**
 * Triggers a client-side file download in the browser.
 */
function triggerBrowserDownload(content: string, filename: string, mimeType: string): void {
  if (typeof window === 'undefined') return;

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Downloads a report as a formatted JSON bundle.
 */
export function downloadReportAsJson(report: Report, customFilename?: string): void {
  const filename = customFilename || `afterfact-report-${report.id}.json`;
  const jsonText = formatReportAsJson(report);
  triggerBrowserDownload(jsonText, filename, 'application/json;charset=utf-8');
}

/**
 * Downloads a report as a clean Markdown bundle.
 */
export function downloadReportAsMarkdown(report: Report, customFilename?: string): void {
  const filename = customFilename || `afterfact-report-${report.id}.md`;
  const mdText = formatReportAsMarkdown(report);
  triggerBrowserDownload(mdText, filename, 'text/markdown;charset=utf-8');
}

/**
 * Copies the Markdown bundle of the report directly to the clipboard.
 */
export async function copyReportToClipboard(report: Report): Promise<boolean> {
  if (typeof navigator === 'undefined' || !navigator.clipboard) {
    return false;
  }
  try {
    const md = formatReportAsMarkdown(report);
    await navigator.clipboard.writeText(md);
    return true;
  } catch {
    return false;
  }
}
