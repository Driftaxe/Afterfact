import { z } from 'zod';
import { ClaimSpanSchema } from './claim';
import { CalendarDateOrTimestampSchema } from './dates';
import { VerificationPropertySchema } from './claim-ticket';
import { DecisionRecordSchema } from './decision';
import { CorrectionSchema } from './report';

/**
 * Verified factual basis extracted from evidence that establishes the true/current value.
 */
export const ReplacementBasisSchema = z.object({
  entity: z.string().min(1, { message: 'Entity is required' }),
  propertyKey: z.string().min(1, { message: 'Property key is required' }),
  previousValue: z.unknown().optional(),
  replacementValue: z.unknown(),
  targetTime: z.string().min(1, { message: 'Target time is required' }),
  applicableScope: z.array(VerificationPropertySchema).default([]),
  evidenceUnitIds: z.array(z.string().min(1)).min(1, {
    message: 'At least one evidence unit ID is required to establish replacement basis',
  }),
  effectiveDate: CalendarDateOrTimestampSchema.optional(),
  summary: z.string().min(1, { message: 'Replacement basis summary is required' }),
});
export type ReplacementBasis = z.infer<typeof ReplacementBasisSchema>;

/**
 * Proposed draft generated by Bifrost (Pass 6: Surgical Correction).
 */
export const CorrectionDraftSchema = z.object({
  draftId: z.string().min(1, { message: 'Draft ID is required' }),
  attemptNumber: z.number().int().min(1),
  replacementText: z.string().min(1, { message: 'Replacement text is required' }),
  rationale: z.string().default(''),
  modelUsed: z.string().optional(),
});
export type CorrectionDraft = z.infer<typeof CorrectionDraftSchema>;

/**
 * Structural exact-span edit against immutable original answer text.
 */
export const ExactSpanEditSchema = z.object({
  editId: z.string().min(1, { message: 'Edit ID is required' }),
  claimId: z.string().min(1, { message: 'Claim ID is required' }),
  claimRevision: z.number().int().min(1),
  answerHash: z.string().min(1, { message: 'Answer hash is required' }),
  span: ClaimSpanSchema,
  expectedOriginalText: z.string().min(1, { message: 'Expected original text is required' }),
  replacementText: z.string().min(1, { message: 'Replacement text is required' }),
  diff: z.string().min(1, { message: 'Diff is required' }),
  verifiedCorrectionId: z.string().optional(),
  evidenceIds: z.array(z.string()).default([]),
});
export type ExactSpanEdit = z.infer<typeof ExactSpanEditSchema>;

/**
 * Comprehensive lifecycle status for a claim's correction pipeline.
 */
export const CorrectionLifecycleStatusSchema = z.enum([
  'not_eligible',                       // Verdict not outdated/contradicted or historical truth
  'no_replacement_basis',               // Contradicted/outdated without established replacement evidence
  'missing_prerequisites',              // Upstream facts/models unavailable
  'draft_generated',                    // Bifrost generated candidate replacement
  'reverification_passed_score_100',    // Candidate achieved score 100 via A05 decideClaim
  'withheld_score_below_threshold',     // Candidate scored 75, 0, or null
  'withheld_extra_assertion_unsupported', // Candidate introduced unsupported assertions
  'span_resolution_failed',             // Claim has no valid/resolvable sourceSpan in answerText
  'provider_error',                     // Bifrost model timeout, refusal, or transport failure
  'budget_exhausted',                   // Max attempts reached without success
  'stale_revision',                     // Answer or claim revision shifted
]);
export type CorrectionLifecycleStatus = z.infer<typeof CorrectionLifecycleStatusSchema>;

/**
 * Detailed result of correction orchestration for an individual claim.
 */
export interface CorrectionOrchestrationResult {
  status: CorrectionLifecycleStatus;
  claimTicketId: string;
  claimRevision: number;
  originalVerdict: string;
  originalScore: number | null;
  eligible: boolean;
  draft: CorrectionDraft | null;
  candidateDecision: z.infer<typeof DecisionRecordSchema> | null;
  edit: ExactSpanEdit | null;
  publicCorrection: z.infer<typeof CorrectionSchema> | null;
  isStandaloneSuggestion: boolean;
  reason: string;
  limitations: string[];
}
